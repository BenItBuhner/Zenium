#!/usr/bin/env node
/**
 * Refresh the bundled snapshot of Mozilla's translation-model registry.
 *
 * Firefox Translations publishes its Bergamot models through Remote Settings (collection
 * `translations-models`): one record per file (model, lex shortlist, vocab) with the SHA-256, the
 * size and the CDN location. This script condenses those records to the newest release per
 * language pair and writes them as a TypeScript module the core ships with, so translation works
 * offline right after a model has been downloaded once and the pair list is known before the
 * first network round trip. The live collection is consulted again at runtime (see
 * `src/core/translate/registry.ts`); this file is the fallback and the first answer.
 *
 *   node scripts/translate-registry.mjs            # fetch and rewrite src/core/translate/registryData.ts
 *   node scripts/translate-registry.mjs records.json  # condense an already downloaded records document
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const RECORDS_URL =
  'https://firefox.settings.services.mozilla.com/v1/buckets/main/collections/translations-models/records'
const LOCATION_PREFIX = 'main-workspace/translations-models/'
const OUT = resolve(import.meta.dirname, '../src/core/translate/registryData.ts')

async function loadRecords(argument) {
  if (argument) return JSON.parse(readFileSync(argument, 'utf8'))
  const response = await fetch(RECORDS_URL)
  if (!response.ok) throw new Error(`Remote Settings answered ${response.status}`)
  return response.json()
}

/**
 * `2.1a1` → [2, 1, 0, 1] and `2.1` → [2, 1, 1, 0]: alphas sort below the release with the same
 * number and among themselves by their alpha number. Mirrors src/core/translate/registry.ts.
 */
function versionKey(version) {
  const match = /^(\d+)\.(\d+)(a(\d*))?$/.exec(version)
  if (!match) return [0, 0, -1, 0]
  return [Number(match[1]), Number(match[2]), match[3] ? 0 : 1, Number(match[4] || 0)]
}

function compareVersions(a, b) {
  const ka = versionKey(a)
  const kb = versionKey(b)
  for (let i = 0; i < 4; i++) if (ka[i] !== kb[i]) return ka[i] - kb[i]
  return 0
}

function condense(records) {
  const byPair = new Map()
  for (const record of records) {
    if (!record.fromLang || !record.toLang || !record.attachment) continue
    const key = `${record.fromLang}\u0000${record.toLang}`
    let versions = byPair.get(key)
    if (!versions) byPair.set(key, (versions = new Map()))
    let files = versions.get(record.version)
    if (!files) versions.set(record.version, (files = new Map()))
    files.set(record.fileType, record)
  }
  const models = []
  for (const [key, versions] of byPair) {
    const complete = [...versions.entries()].filter(([, files]) => {
      return (
        files.has('model') &&
        files.has('lex') &&
        (files.has('vocab') || (files.has('srcvocab') && files.has('trgvocab')))
      )
    })
    if (complete.length === 0) continue
    // Firefox prefers releases over alphas of the same pair; an alpha only ships when nothing else does.
    const releases = complete.filter(([version]) => !/a/.test(version))
    const candidates = releases.length > 0 ? releases : complete
    candidates.sort((a, b) => compareVersions(b[0], a[0]))
    const [version, files] = candidates[0]
    const [from, to] = key.split('\u0000')
    const file = (type) => {
      const record = files.get(type)
      const location = record.attachment.location
      return {
        t: type,
        s: record.attachment.size,
        h: record.attachment.hash,
        l: location.startsWith(LOCATION_PREFIX) ? location.slice(LOCATION_PREFIX.length) : location
      }
    }
    const list = [file('model'), file('lex')]
    if (files.has('srcvocab') && files.has('trgvocab'))
      list.push(file('srcvocab'), file('trgvocab'))
    else list.push(file('vocab'))
    models.push({ f: from, o: to, v: version, x: list })
  }
  models.sort((a, b) => (a.f + a.o).localeCompare(b.f + b.o))
  return models
}

function render(models, fetchedAt) {
  const lines = models.map((m) => `  ${JSON.stringify(m)}`)
  return `/**
 * Snapshot of Mozilla's translation-model registry (Remote Settings collection
 * \`translations-models\`), condensed to the newest release per language pair. Generated by
 * \`scripts/translate-registry.mjs\`; do not edit by hand. Model files are CC-BY-SA-4.0 (or as
 * stated per model at mozilla/firefox-translations-models) and are downloaded on demand, never
 * bundled.
 */
import type { PackedModel } from './registryTypes'

export const REGISTRY_SNAPSHOT_AT = '${fetchedAt}'
export const REGISTRY_LOCATION_PREFIX = '${LOCATION_PREFIX}'

// prettier-ignore
export const REGISTRY_SNAPSHOT: PackedModel[] = [
${lines.join(',\n')}
]
`
}

const document = await loadRecords(process.argv[2])
const records = Array.isArray(document) ? document : document.data
const models = condense(records)
writeFileSync(OUT, render(models, new Date().toISOString().slice(0, 10)))
const languages = new Set()
for (const m of models) {
  languages.add(m.f)
  languages.add(m.o)
}
const bytes = models.reduce((sum, m) => sum + m.x.reduce((s, f) => s + f.s, 0), 0)
console.log(
  `${models.length} pairs, ${languages.size} languages, ${(bytes / 1e9).toFixed(2)} GB of models; wrote ${OUT}`
)
