export interface IconImage {
  size: number
  png: Uint8Array
}

/** Windows icon: a directory of PNG-compressed images (Vista and later). */
export function encodeIco(images: IconImage[]): Uint8Array {
  const header = new Uint8Array(6)
  const hv = new DataView(header.buffer)
  hv.setUint16(0, 0, true)
  hv.setUint16(2, 1, true)
  hv.setUint16(4, images.length, true)
  const directory = new Uint8Array(16 * images.length)
  const dv = new DataView(directory.buffer)
  let offset = header.length + directory.length
  images.forEach((image, i) => {
    const o = i * 16
    // 256 is stored as 0 (the field is one byte).
    directory[o] = image.size >= 256 ? 0 : image.size
    directory[o + 1] = image.size >= 256 ? 0 : image.size
    directory[o + 2] = 0
    directory[o + 3] = 0
    dv.setUint16(o + 4, 1, true)
    dv.setUint16(o + 6, 32, true)
    dv.setUint32(o + 8, image.png.length, true)
    dv.setUint32(o + 12, offset, true)
    offset += image.png.length
  })
  return concat([header, directory, ...images.map((i) => i.png)])
}

/** The sizes listed in an ICO directory, in order. */
export function icoSizes(ico: Uint8Array): number[] {
  const view = new DataView(ico.buffer, ico.byteOffset, ico.byteLength)
  if (view.getUint16(2, true) !== 1) throw new Error('not an ICO')
  const count = view.getUint16(4, true)
  const sizes: number[] = []
  for (let i = 0; i < count; i++) {
    const w = ico[6 + i * 16]
    sizes.push(w === 0 ? 256 : w)
  }
  return sizes
}

/** macOS icon family: 'icns', total length, then `type` + length + PNG for every entry. */
export function encodeIcns(entries: Array<{ type: string; png: Uint8Array }>): Uint8Array {
  const encoder = new TextEncoder()
  const blocks = entries.map((e) => concat([encoder.encode(e.type), u32(8 + e.png.length), e.png]))
  const total = 8 + blocks.reduce((n, b) => n + b.length, 0)
  return concat([encoder.encode('icns'), u32(total), ...blocks])
}

/** The entry types of an ICNS file, in order. */
export function icnsTypes(icns: Uint8Array): string[] {
  const view = new DataView(icns.buffer, icns.byteOffset, icns.byteLength)
  if (String.fromCharCode(...icns.subarray(0, 4)) !== 'icns') throw new Error('not an ICNS')
  const total = view.getUint32(4)
  if (total !== icns.length) throw new Error('ICNS length mismatch')
  const types: string[] = []
  let offset = 8
  while (offset < total) {
    types.push(String.fromCharCode(...icns.subarray(offset, offset + 4)))
    offset += view.getUint32(offset + 4)
  }
  return types
}

