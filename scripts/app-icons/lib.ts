/**
 * Everything `scripts/app-icons.ts` needs to turn `src/shared/appIcon.ts` into files, as pure
 * functions so the test suite can check the plan without touching the repository:
 *
 *  - a rasteriser for the mark on its squircle ground (signed distances, one sample per pixel,
 *    so every size is rendered natively and identically on every machine),
 *  - PNG, ICO and ICNS encoders (PNG-compressed entries; only `node:zlib` is used),
 *  - the Android resources (adaptive-icon layers, colours, the launcher aliases block of the
 *    manifest) and the Kotlin table of alias names.
 */
