/** `indigo` → `Indigo`: the alias class inside `app.zen.chromium.icon`. */
export function aliasClass(variant: Pick<AppIconVariant, 'id'>): string {
  return `${ANDROID_NAMESPACE}.icon.${variant.id[0].toUpperCase()}${variant.id.slice(1)}`
}

export function androidColorName(variant: Pick<AppIconVariant, 'id'>): string {
  return `ic_launcher_bg_${variant.id}`
}

export function androidMipmapName(variant: Pick<AppIconVariant, 'id'>): string {
  return `ic_launcher_${variant.id}`
}

/** The mark as a vector drawable in the 108 dp adaptive-icon canvas (foreground and monochrome). */
export function androidForegroundXml(): string {
  const { canvas, ringOuter } = APP_ICON_ANDROID
  const c = canvas / 2
  const ring = round(ringOuter * APP_ICON_MARK.ring)
  const stroke = round(ringOuter * APP_ICON_MARK.stroke)
  const dot = round(ringOuter * APP_ICON_MARK.dot)
  const ink = APP_ICON_INK.replace('#', '#FF').toUpperCase()
  // A full circle as an arc that ends a hair from where it starts (an arc back to its own start
  // point is degenerate and disappears).
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<!-- Zenium's mark: a ring with a dot, white; the launcher tints the monochrome copy itself. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${canvas}dp"
    android:height="${canvas}dp"
    android:viewportWidth="${canvas}"
    android:viewportHeight="${canvas}">
    <path
        android:fillColor="#00000000"
        android:strokeColor="${ink}"
        android:strokeWidth="${stroke}"
        android:pathData="M${c},${round(c - ring)} a${ring},${ring} 0 1,0 0.01,0 Z" />
    <path
        android:fillColor="${ink}"
        android:pathData="M${c},${round(c - dot)} a${dot},${dot} 0 1,0 0.01,0 Z" />
</vector>
`
}

export function androidColorsXml(variants: readonly AppIconVariant[]): string {
  const lines = variants.map(
    (v) => `    <color name="${androidColorName(v)}">${v.fill.toUpperCase()}</color>`
  )
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<resources>
${lines.join('\n')}
</resources>
`
}

export function androidAdaptiveIconXml(variant: AppIconVariant): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${androidColorName(variant)}" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`
}

/**
 * One launcher alias per variant, only the default enabled in the manifest; `LauncherIcon.kt`
 * flips them at runtime. They target `LauncherIconActivity`, which starts `MainActivity` in a
 * task of its own: a task rooted at an alias would be removed the moment that alias is disabled.
 * Deep links, share and search intents stay on `MainActivity` itself.
 */
export function manifestAliasesBlock(
  variants: readonly AppIconVariant[],
  indent = '        '
): string {
  const aliases = variants.map((v) => {
    const relative = aliasClass(v).slice(ANDROID_NAMESPACE.length)
    return `${indent}<activity-alias
${indent}    android:name="${relative}"
${indent}    android:enabled="${v.id === APP_ICON_DEFAULT}"
${indent}    android:exported="true"
${indent}    android:icon="@mipmap/${androidMipmapName(v)}"
${indent}    android:label="@string/app_name"
${indent}    android:targetActivity=".LauncherIconActivity">
${indent}    <intent-filter>
${indent}        <action android:name="android.intent.action.MAIN" />
${indent}        <category android:name="android.intent.category.LAUNCHER" />
${indent}    </intent-filter>
${indent}</activity-alias>`
  })
  return `${indent}${MANIFEST_BEGIN} (${GENERATED}) -->\n${aliases.join('\n')}\n${indent}${MANIFEST_END}`
}

/** The manifest with its aliases block regenerated in place (the markers must exist). */
export function manifestWithAliases(manifest: string, variants: readonly AppIconVariant[]): string {
  const begin = manifest.indexOf(MANIFEST_BEGIN)
  const end = manifest.indexOf(MANIFEST_END)
  if (begin < 0 || end < begin)
    throw new Error(`${ANDROID_MANIFEST} has no app-icon-aliases markers`)
  const lineStart = manifest.lastIndexOf('\n', begin) + 1
  const indent = manifest.slice(lineStart, begin)
  return (
    manifest.slice(0, lineStart) +
    manifestAliasesBlock(variants, indent) +
    manifest.slice(end + MANIFEST_END.length)
  )
}

export function kotlinVariantsSource(variants: readonly AppIconVariant[]): string {
  const entries = variants.map((v) => `        "${v.id}" to "${aliasClass(v)}"`).join(',\n')
  return `// ${GENERATED}
package ${ANDROID_NAMESPACE}

/** The launcher icon variants: id → the \`activity-alias\` that carries that icon. */
object LauncherIconVariants {
    const val DEFAULT = "${APP_ICON_DEFAULT}"

    val ALIASES: Map<String, String> = linkedMapOf(
${entries}
    )
}
`
}

function round(v: number): number {
  return Math.round(v * 100) / 100
}

