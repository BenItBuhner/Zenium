export interface PlanInput {
  /** Current text of the Android manifest (its aliases block is regenerated). */
  manifest: string
  variants?: readonly AppIconVariant[]
}

/** Every file the generator writes, for all variants. */
export function planAppIcons(input: PlanInput): OutputFile[] {
  const variants = input.variants ?? APP_ICON_VARIANTS
  const fallback = variants.find((v) => v.id === APP_ICON_DEFAULT) ?? variants[0]
  const files: OutputFile[] = []
  const png = (variant: AppIconVariant, size: number, opts?: RenderOptions): Uint8Array =>
    encodePng(renderIcon(variant, size, opts), size)
  const ico = (variant: AppIconVariant): Uint8Array =>
    encodeIco(ICO_SIZES.map((size) => ({ size, png: png(variant, size) })))

  for (const variant of variants) {
    const dir = `${RUNTIME_ICON_DIR}/${variant.id}`
    files.push({ path: `${dir}/icon.png`, data: png(variant, DESKTOP_PNG_SIZE) })
    files.push({ path: `${dir}/icon.ico`, data: ico(variant) })
    files.push({ path: `${dir}/dock.png`, data: png(variant, DOCK_PNG_SIZE, { macInset: true }) })
    files.push({
      path: `${ANDROID_RES}/mipmap-anydpi-v26/${androidMipmapName(variant)}.xml`,
      data: androidAdaptiveIconXml(variant)
    })
  }

  // electron-builder's inputs: the default variant.
  files.push({ path: 'build/icon.png', data: png(fallback, DESKTOP_PNG_SIZE) })
  files.push({ path: 'build/icon.ico', data: ico(fallback) })
  files.push({
    path: 'build/icon.icns',
    data: encodeIcns(
      ICNS_TYPES.map((e) => ({ type: e.type, png: png(fallback, e.size, { macInset: true }) }))
    )
  })

  // The application icon (Settings → Apps, the installer prompt) is the default variant too.
  files.push({
    path: `${ANDROID_RES}/mipmap-anydpi-v26/ic_launcher.xml`,
    data: androidAdaptiveIconXml(fallback)
  })
  files.push({
    path: `${ANDROID_RES}/drawable/ic_launcher_foreground.xml`,
    data: androidForegroundXml()
  })
  files.push({
    path: `${ANDROID_RES}/values/ic_launcher_colors.xml`,
    data: androidColorsXml(variants)
  })
  files.push({ path: ANDROID_MANIFEST, data: manifestWithAliases(input.manifest, variants) })
  files.push({ path: KOTLIN_VARIANTS, data: kotlinVariantsSource(variants) })
  return files
}
